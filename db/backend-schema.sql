-- ============================================================================
-- Fruit Rush Backend Application Schema
-- ============================================================================
-- Tables used directly by the Express backend and Supabase service-role client.
-- Run this in Supabase SQL Editor after creating the project.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.game_sessions (
  session_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  player_id TEXT NOT NULL,
  game_mode TEXT NOT NULL CHECK (game_mode IN ('Classic', 'Zen', 'Arcade', 'Tournament')),
  client_score INTEGER NOT NULL CHECK (client_score >= 0),
  server_score INTEGER NOT NULL CHECK (server_score >= 0),
  combo_highwater INTEGER NOT NULL DEFAULT 0 CHECK (combo_highwater >= 0),
  duration_seconds NUMERIC NOT NULL CHECK (duration_seconds > 0),
  client_timestamp TIMESTAMPTZ NOT NULL,
  server_timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  input_event_count INTEGER NOT NULL CHECK (input_event_count >= 0),
  score_divergence NUMERIC NOT NULL DEFAULT 0,
  valid BOOLEAN NOT NULL DEFAULT FALSE,
  rejection_reason TEXT,
  boast_nonce NUMERIC,
  boast_signed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_game_sessions_game_mode_score
  ON public.game_sessions (game_mode, server_score DESC);
CREATE INDEX IF NOT EXISTS idx_game_sessions_player
  ON public.game_sessions (player_id);
CREATE INDEX IF NOT EXISTS idx_game_sessions_valid_timestamp
  ON public.game_sessions (valid, server_timestamp DESC);

CREATE TABLE IF NOT EXISTS public.tournaments (
  tournament_id TEXT PRIMARY KEY,
  entry_fee_wei TEXT NOT NULL,
  start_time TIMESTAMPTZ NOT NULL,
  end_time TIMESTAMPTZ NOT NULL,
  prize_shares_bps INTEGER[] NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('Pending', 'Open', 'Closed', 'Finalized', 'Refunded')),
  template_name TEXT,
  creation_tx_hash TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  finalized_at TIMESTAMPTZ,
  finalization_tx_hash TEXT,
  winner_count INTEGER NOT NULL DEFAULT 0 CHECK (winner_count >= 0),
  refunded_at TIMESTAMPTZ,
  refund_tx_hash TEXT,
  notes TEXT
);

CREATE INDEX IF NOT EXISTS idx_tournaments_status
  ON public.tournaments (status);
CREATE INDEX IF NOT EXISTS idx_tournaments_end_time
  ON public.tournaments (end_time DESC);
CREATE INDEX IF NOT EXISTS idx_tournaments_pending_finalization
  ON public.tournaments (end_time)
  WHERE status IN ('Pending', 'Open');

CREATE TABLE IF NOT EXISTS public.tournament_entries (
  entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id TEXT NOT NULL REFERENCES public.tournaments(tournament_id) ON DELETE CASCADE,
  player_address TEXT NOT NULL,
  entered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (tournament_id, player_address)
);

CREATE INDEX IF NOT EXISTS idx_tournament_entries_player
  ON public.tournament_entries (player_address);
CREATE INDEX IF NOT EXISTS idx_tournament_entries_tournament
  ON public.tournament_entries (tournament_id);
CREATE INDEX IF NOT EXISTS idx_tournament_entries_entered_at
  ON public.tournament_entries (entered_at DESC);

ALTER TABLE public.game_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tournaments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tournament_entries ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public read access for tournaments" ON public.tournaments;
CREATE POLICY "Public read access for tournaments"
  ON public.tournaments FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "Public read access for tournament entries" ON public.tournament_entries;
CREATE POLICY "Public read access for tournament entries"
  ON public.tournament_entries FOR SELECT
  USING (true);
